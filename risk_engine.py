
def calculate_risk(text: str, scam_type: str = ""):
    text_lower = text.lower()

    score = 0
    indicators = []

    def add_score(points, indicator):
        nonlocal score
        score += points
        if indicator not in indicators:
            indicators.append(indicator)

    # =========================================================
    # 1. БАНКОВСКИЕ ДАННЫЕ
    # =========================================================

    card_words = [
        "карту",
        "карта",
        "банковскую карту",
        "номер карты",
        "данные карты",
        "реквизиты карты",
        "счёт",
        "счет",
        "банковский счёт",
        "банковский счет",
        "на карту"
    ]

    if any(word in text_lower for word in card_words):
        add_score(
            20,
            "Запрашиваются данные банковской карты или счёта"
        )

    # =========================================================
    # 2. КОД ИЗ SMS / ПАРОЛЬ
    # =========================================================

    sms_words = [
        "код из sms",
        "код из смс",
        "код подтверждения",
        "код подтверждения из sms",
        "код подтверждения из смс",
        "одноразовый код",
        "одноразовый пароль",
        "код из сообщения",
        "код из сообщения sms",
        "код из сообщения смс",
    ]

    if any(word in text_lower for word in sms_words):
        add_score(
            35,
            "Запрашивается код из SMS или другой код подтверждения"
        )

    # =========================================================
    # 3. PIN / CVV / CVC
    # =========================================================

    security_words = [
        "pin",
        "пин-код",
        "пин код",
        "cvv",
        "cvc",
        "секретный код",
        "пароль от банка",
        "пароль от банковского приложения"
    ]

    if any(word in text_lower for word in security_words):
        add_score(
            30,
            "Запрашиваются секретные данные для доступа к банковскому аккаунту"
        )

    # =========================================================
    # 4. ПРЕДСТАВЛЕНИЕ СОТРУДНИКОМ БАНКА
    # =========================================================

    bank_employee_words = [
        "сотрудник банка",
        "сотрудник службы безопасности банка",
        "служба безопасности банка",
        "безопасность банка",
        "банк сообщает",
        "мы из банка",
        "я из банка",
        "представитель банка",
        "служба безопасности"
    ]

    if any(word in text_lower for word in bank_employee_words):
        add_score(
            20,
            "Отправитель представляется сотрудником банка или службы безопасности"
        )

    # =========================================================
    # 5. УГРОЗА СПИСАНИЯ / ПРОБЛЕМА С ДЕНЬГАМИ
    # =========================================================

    money_threat_words = [
        "деньги будут списаны",
        "деньги спишут",
        "деньги спишутся",
        "спишут деньги",
        "списание денег",
        "списание с карты",
        "списывают деньги",
        "пытаются снять деньги",
        "снять деньги",
        "подозрительная операция",
        "подозрительную операцию",
        "операция по вашей карте",
        "транзакция",
        "неизвестная операция"
    ]

    if any(word in text_lower for word in money_threat_words):
        add_score(
            20,
            "Используется информация об угрозе потери или списания денег"
        )

    # =========================================================
    # 6. СРОЧНОСТЬ И ДАВЛЕНИЕ
    # =========================================================

    urgent_words = [
        "срочно",
        "немедленно",
        "прямо сейчас",
        "только сегодня",
        "в течение 5 минут",
        "в течение 10 минут",
        "у вас есть 5 минут",
        "у вас есть 10 минут",
        "как можно скорее",
        "незамедлительно"
    ]

    if any(word in text_lower for word in urgent_words):
        add_score(
            15,
            "Используется давление и искусственная срочность"
        )

    # =========================================================
    # 7. ЗАПРОС ЛИЧНЫХ ДАННЫХ
    # =========================================================

    personal_data_words = [
        "паспорт",
        "номер паспорта",
        "паспортные данные",
        "номер телефона",
        "дата рождения",
        "личные данные",
        "персональные данные",
        "кодовое слово"
    ]

    if any(word in text_lower for word in personal_data_words):
        add_score(
            15,
            "Запрашиваются личные или персональные данные"
        )

    # =========================================================
    # 8. НЕ ПЕРЕДАВАТЬ ИНФОРМАЦИЮ ДРУГИМ
    # =========================================================

    secrecy_words = [
        "никому не рассказывайте",
        "никому не говорите",
        "не рассказывайте никому",
        "никому не сообщайте",
        "не сообщайте никому",
        "держите это в секрете",
        "никому не говорите об этом"
    ]

    if any(word in text_lower for word in secrecy_words):
        add_score(
            15,
            "Отправитель требует скрывать происходящее от других людей"
        )

    # =========================================================
    # 9. ССЫЛКИ / ПЕРЕХОД НА САЙТ
    # =========================================================

    link_words = [
        "перейдите по ссылке",
        "перейдите по этой ссылке",
        "откройте ссылку",
        "нажмите на ссылку",
        "перейдите на сайт",
        "введите данные на сайте",
        "введите данные карты"
    ]

    if any(word in text_lower for word in link_words):
        add_score(
            20,
            "Предлагается перейти по ссылке или ввести данные на сайте"
        )

    # =========================================================
    # 10. ПОЛУЧЕНИЕ ЧУЖИХ ДЕНЕГ
    # =========================================================

    money_words = [
        "принимайте деньги",
        "принимать деньги",
        "получать деньги",
        "получать переводы",
        "переводить их дальше",
        "переводить деньги",
        "переводите их дальше",
        "переводить дальше"
    ]

    if any(word in text_lower for word in money_words):
        add_score(
            30,
            "Предлагается получение и последующий перевод чужих денежных средств"
        )

    # =========================================================
    # 11. ВЫСОКИЙ ДОХОД
    # =========================================================

    income_words = [
        "300 000",
        "500 000",
        "100 000",
        "высокий доход",
        "лёгкие деньги",
        "легкие деньги",
        "большой доход"
    ]

    if any(word in text_lower for word in income_words):
        add_score(
            15,
            "Обещается необычно высокий или лёгкий доход"
        )

    # =========================================================
    # 12. РАБОТА БЕЗ ОПЫТА
    # =========================================================

    if "без опыта" in text_lower or "опыт не нужен" in text_lower:
        add_score(
            10,
            "Предлагается работа без опыта или квалификации"
        )

    # =========================================================
    # 13. ПРОЦЕНТ ЗА ОПЕРАЦИИ
    # =========================================================

    if "%" in text_lower or "процент" in text_lower:
        add_score(
            10,
            "Предлагается процент за проведение финансовых операций"
        )

    # =========================================================
    # 14. ТИП МОШЕННИЧЕСТВА ОТ AI
    # =========================================================

    scam_type_lower = scam_type.lower()

    high_risk_types = [
        "фальшивый сотрудник банка",
        "фишинг",
        "дропперская схема"
    ]

    if any(scam in scam_type_lower for scam in high_risk_types):
        add_score(
            15,
            "AI определил тип схемы с высоким риском мошенничества"
        )

    # =========================================================
    # ОГРАНИЧЕНИЕ 0-100
    # =========================================================

    score = min(score, 100)

    # =========================================================
    # УРОВЕНЬ РИСКА
    # =========================================================

    if score >= 70:
        level = "HIGH"
    elif score >= 40:
        level = "MEDIUM"
    else:
        level = "LOW"

    return {
        "risk_score": score,
        "risk_level": level,
        "indicators": indicators
    }
